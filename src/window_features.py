"""J26-CS-336: reusable UTC tumbling-window features for VERIFIED packet events.

This module never reads a dataset, infers attack labels, or assigns asset IDs.
Its caller must supply one PacketEvent per *verified* packet and an asset_id.
The public CICAPT CSV has not yet been verified as exactly one packet per row.

Definitions:
* Windows are [start, end), aligned to UTC Unix-epoch multiples of 5/10/15/20 s.
* flow_count counts distinct bidirectional (IP, port, protocol) keys INSIDE a window;
  it is not a lifetime TCP session count.
* mean_iat_seconds is the mean of consecutive arrival-time gaps across all
  packets for the SAME asset INSIDE the window, not a per-flow IAT.
* unique_dst_ports counts all observed directed packet destinations, including
  reply ports; it is not by itself a reliable port-scan signal.
* Empty windows are not emitted. A single-packet window has mean_iat_seconds=None.
* No attack label, ground truth, or ML inference is generated by this module.
"""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from statistics import mean
from typing import Iterable

WINDOW_SIZES = (5, 10, 15, 20)
TCP_FLAGS = ("fin", "syn", "rst", "psh", "ack", "urg", "ece", "cwr")


@dataclass(frozen=True)
class PacketEvent:
    ts: datetime
    asset_id: str
    src_ip: str
    dst_ip: str
    src_port: int
    dst_port: int
    protocol: int
    size_bytes: int
    fin: int = 0
    syn: int = 0
    rst: int = 0
    psh: int = 0
    ack: int = 0
    urg: int = 0
    ece: int = 0
    cwr: int = 0


def _validated_time(ts: datetime) -> datetime:
    if not isinstance(ts, datetime) or ts.tzinfo is None or ts.utcoffset() != timedelta(0):
        raise ValueError("Each packet timestamp must be a timezone-aware UTC datetime")
    return ts


def _check_packet(p: PacketEvent) -> None:
    _validated_time(p.ts)
    if not p.asset_id or not p.src_ip or not p.dst_ip:
        raise ValueError("asset_id, src_ip, and dst_ip are required")
    if type(p.size_bytes) is not int or p.size_bytes <= 0:
        raise ValueError("size_bytes must be a positive integer")
    if type(p.protocol) is not int or not 0 <= p.protocol <= 255:
        raise ValueError("protocol must be an integer between 0 and 255")
    if any(type(port) is not int or not 0 <= port <= 65535 for port in (p.src_port, p.dst_port)):
        raise ValueError("Ports must be integers between 0 and 65535")
    if any(getattr(p, flag) not in (0, 1) for flag in TCP_FLAGS):
        raise ValueError("TCP flags must each be 0 or 1")


def _window_start(ts: datetime, seconds: int) -> datetime:
    return datetime.fromtimestamp(int(_validated_time(ts).timestamp() // seconds) * seconds, tz=timezone.utc)


def _iso_z(ts: datetime) -> str:
    return ts.isoformat().replace("+00:00", "Z")


def _bidirectional_flow(p: PacketEvent) -> tuple:
    endpoints = tuple(sorted(((p.src_ip, p.src_port), (p.dst_ip, p.dst_port))))
    return (p.protocol, endpoints)


def build_window_features(events: Iterable[PacketEvent], seconds: int) -> list[dict]:
    """Aggregate supplied packet events into nonempty, per-asset UTC windows."""
    if seconds not in WINDOW_SIZES:
        raise ValueError(f"Window must be one of {WINDOW_SIZES}")

    grouped = defaultdict(list)
    for packet in events:
        _check_packet(packet)
        grouped[(packet.asset_id, _window_start(packet.ts, seconds))].append(packet)

    result: list[dict] = []
    for (asset_id, start), packets in sorted(grouped.items()):
        ordered = sorted(packets, key=lambda packet: packet.ts)
        n_packets = len(ordered)
        total_bytes = sum(p.size_bytes for p in ordered)
        gaps = [(b.ts - a.ts).total_seconds() for a, b in zip(ordered, ordered[1:])]
        tcp = [p for p in ordered if p.protocol == 6]

        features = {
            "asset_id": asset_id,
            "window_start": _iso_z(start),
            "window_end": _iso_z(start + timedelta(seconds=seconds)),
            "window_seconds": seconds,
            "packet_count": n_packets,
            "total_bytes": total_bytes,
            "mean_packet_size": round(total_bytes / n_packets, 4),
            "tcp_packet_count": len(tcp),
            "unique_dst_ports": len({p.dst_port for p in ordered}),
            "unique_dst_ips": len({p.dst_ip for p in ordered}),
            "flow_count": len({_bidirectional_flow(p) for p in ordered}),
            "packet_rate_per_second": round(n_packets / seconds, 4),
            "byte_rate_per_second": round(total_bytes / seconds, 4),
            "mean_iat_seconds": round(mean(gaps), 4) if gaps else None,
        }
        for flag in TCP_FLAGS:
            features[f"{flag}_packet_count"] = sum(getattr(p, flag) for p in tcp)
        result.append(features)

    return result
